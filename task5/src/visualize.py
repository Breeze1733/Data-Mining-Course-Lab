"""Draw the task5 analysis figures from the mapping table (reproducible replacements for the
historical figures that the previous iteration generated by hand).

Input : task5/output/mapping_table.json (frequency-weighted)
Output: task5/output/figs/cond_type_by_scenic.png  条件类型 × 景区（含无显式条件单列）
        task5/output/figs/crowd_breakdown.png      人群类条件的游客类型 × 景区
        task5/output/figs/condition_provenance.png 抽取模式 × 极性
Run   : python task5/src/visualize.py  (repo root)
"""
from __future__ import annotations

import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "output"
FIGS = OUT / "figs"

sys.stdout.reconfigure(encoding="utf-8")
plt.rcParams["font.sans-serif"] = ["SimHei", "Microsoft YaHei"]
plt.rcParams["axes.unicode_minus"] = False

SCENICS = ["黄山", "九寨沟", "颐和园"]
SCENIC_COLORS = {"黄山": "#C62828", "九寨沟": "#1565C0", "颐和园": "#2E7D32"}

CROWD_WORDS = ("老人", "孩子", "小孩", "儿童", "婴儿", "亲子", "带娃", "情侣", "夫妻", "孕妇",
               "腿脚", "体力", "新手", "第一次", "学生", "家庭", "恐高", "晕车")


def crowd_label(row: dict) -> str:
    text = row.get("condition_text") or row.get("condition_label") or ""
    for w in CROWD_WORDS:
        if w in text:
            return w
    return "未细分"


def save(fig, name: str) -> None:
    FIGS.mkdir(parents=True, exist_ok=True)
    fig.savefig(FIGS / name, bbox_inches="tight")
    plt.close(fig)
    print(name)


def main() -> int:
    mapping = json.loads((OUT / "mapping_table.json").read_text(encoding="utf-8"))

    # Figure 1: condition type × scenic area (absent conditions listed separately).
    by_type = defaultdict(Counter)
    for r in mapping:
        key = r["condition_type"] if r["condition_text"] else "无显式条件"
        by_type[key][r["scenic_area"]] += r["frequency"]
    order = [k for k, _ in sorted(by_type.items(), key=lambda kv: -sum(kv[1].values()))]
    fig, ax = plt.subplots(figsize=(11.5, 4.6), dpi=150)
    bottom = [0.0] * len(SCENICS)
    for key in order:
        vals = [by_type[key].get(s, 0) for s in SCENICS]
        ax.bar(SCENICS, vals, 0.55, bottom=bottom, label=key, alpha=0.88)
        bottom = [b + v for b, v in zip(bottom, vals)]
    for i, s in enumerate(SCENICS):
        ax.text(i, bottom[i] + 4, str(int(bottom[i])), ha="center", fontsize=9)
    ax.set_ylabel("频次（去重后行 × 来源数）")
    ax.set_title("条件类型 × 景区分布")
    ax.legend(ncol=3, fontsize=8)
    ax.spines[["top", "right"]].set_visible(False)
    save(fig, "cond_type_by_scenic.png")

    # Figure 2: visitor-type breakdown for 人群-conditions, grouped bars per scenic area.
    by_crowd = defaultdict(Counter)
    for r in mapping:
        if r["condition_type"] == "人群":
            by_crowd[crowd_label(r)][r["scenic_area"]] += r["frequency"]
    order = sorted(by_crowd, key=lambda k: -sum(by_crowd[k].values()))
    xs = range(len(order))
    width = 0.26
    fig, ax = plt.subplots(figsize=(10.5, 4.2), dpi=150)
    for offset, scenic in enumerate(SCENICS):
        vals = [by_crowd[k].get(scenic, 0) for k in order]
        ax.bar([x + (offset - 1) * width for x in xs], vals, width,
               label=scenic, color=SCENIC_COLORS[scenic], alpha=0.88)
    ax.set_xticks(list(xs))
    ax.set_xticklabels(order, fontsize=9)
    ax.set_ylabel("频次")
    ax.set_title("人群类条件建议的游客类型分布")
    ax.legend(fontsize=9)
    ax.spines[["top", "right"]].set_visible(False)
    save(fig, "crowd_breakdown.png")

    # Figure 3: extraction pattern × polarity provenance.
    by_pattern = defaultdict(Counter)
    for r in mapping:
        by_pattern[r["pattern"]][r["polarity"]] += r["frequency"]
    order = [k for k, _ in sorted(by_pattern.items(), key=lambda kv: -sum(kv[1].values()))]
    fig, ax = plt.subplots(figsize=(9.5, 4.0), dpi=150)
    pos = [by_pattern[k].get("POS", 0) for k in order]
    neg = [by_pattern[k].get("NEG", 0) for k in order]
    ax.bar(order, pos, 0.55, label="正向建议", color="#2E7D32", alpha=0.88)
    ax.bar(order, neg, 0.55, bottom=pos, label="负向建议(避雷)", color="#C62828", alpha=0.88)
    for i, (p, n) in enumerate(zip(pos, neg)):
        ax.text(i, p + n + 2, str(p + n), ha="center", fontsize=9)
    ax.set_ylabel("频次")
    ax.set_title("抽取模式 × 极性（去重后映射行）")
    ax.legend(fontsize=9)
    ax.spines[["top", "right"]].set_visible(False)
    save(fig, "condition_provenance.png")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
